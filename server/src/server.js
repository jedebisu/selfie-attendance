// Auto-import NAPs from committed CSV if table is empty
const importNapsIfNeeded = async () => {
  try {
    const countResult = await pool.query('SELECT COUNT(*) FROM naps');
    if (parseInt(countResult.rows[0].count) > 0) {
      console.log('NAPs table has data. Skipping import.');
      return;
    }

    console.log('NAPs table empty. Starting auto-import...');
    const { execSync } = require('child_process');
    const fs = require('fs');
    const path = require('path');
    const readline = require('readline');

    const csvGzPath = path.join(__dirname, 'config/naps_export.csv.gz');
    if (!fs.existsSync(csvGzPath)) {
      console.log('NAP export CSV not found. Skipping import.');
      return;
    }

    const csvPath = csvGzPath.replace('.gz', '');
    execSync(`gunzip -c "${csvGzPath}" > "${csvPath}"`);

    const fileStream = fs.createReadStream(csvPath);
    const rl = readline.createInterface({ input: fileStream, crlfDelay: Infinity });

    const BATCH_SIZE = 2000;
    let imported = 0;
    let batch = [];
    let headerSkipped = false;
    const client = await pool.connect();

    try {
      await client.query('BEGIN');

      for await (const line of rl) {
        if (!headerSkipped) { headerSkipped = true; continue; }

        const fields = parseCSVLine(line);
        if (fields.length < 17) continue;

        batch.push(fields);

        if (batch.length >= BATCH_SIZE) {
          await insertBatch(client, batch);
          imported += batch.length;
          batch = [];
          console.log(`NAP import: ${imported} rows...`);
        }
      }

      if (batch.length > 0) {
        await insertBatch(client, batch);
        imported += batch.length;
      }

      await client.query('COMMIT');
      console.log(`NAP import complete: ${imported} rows.`);

      await client.query('CREATE INDEX IF NOT EXISTS idx_naps_coords ON naps(dp_nap_lat, dp_nap_long)');
      await client.query('CREATE INDEX IF NOT EXISTS idx_naps_nap_id ON naps(nap_id)');
      console.log('NAP indexes created.');

      fs.unlinkSync(csvPath);
    } catch (err) {
      await client.query('ROLLBACK');
      console.error('NAP import failed:', err.message);
    } finally {
      client.release();
      if (fs.existsSync(csvPath)) fs.unlinkSync(csvPath);
    }
  } catch (error) {
    console.error('NAP import check failed:', error.message);
  }
};

function parseCSVLine(line) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') { inQuotes = !inQuotes; }
    else if (char === ',' && !inQuotes) { result.push(current); current = ''; }
    else { current += char; }
  }
  result.push(current);
  return result;
}

async function insertBatch(client, batch) {
  const values = [];
  const placeholders = [];
  batch.forEach((fields, i) => {
    const offset = i * 17;
    placeholders.push(`(${Array.from({ length: 17 }, (_, j) => `$${offset + j + 1}`).join(',')})`);
    values.push(
      fields[0] || null, fields[1] || null, fields[2] || null,
      fields[3] || null, fields[4] || null,
      parseInt(fields[5]) || 0, parseInt(fields[6]) || 0, parseInt(fields[7]) || 0,
      fields[8] || null, fields[9] || null, fields[10] || null,
      parseFloat(fields[11]) || null, parseFloat(fields[12]) || null,
      fields[13] || null, fields[14] || null, fields[15] || null,
      fields[16] || null
    );
  });
  await client.query(`
    INSERT INTO naps (nap_id, cabinet, location_type, building_served, floors_served,
      working_lines, vacant_lines, total_capacity, cfs_region, city_name, province_name,
      dp_nap_lat, dp_nap_long, naps_status, olt_id, sell_status, barangay_name)
    VALUES ${placeholders.join(',')}
    ON CONFLICT (nap_id) DO NOTHING
  `, values);
}

// Session cleanup: delete expired tokens
const cleanupSessions = async () => {
  try {
    const result = await pool.query('DELETE FROM sessions WHERE expires_at < NOW()');
    if (result.rowCount > 0) {
      console.log(`Cleaned up ${result.rowCount} expired sessions`);
    }
  } catch (error) {
    console.error('Session cleanup error:', error.message);
  }
};

// Ensure test users exist with correct bcrypt hashes (runs on every startup)
const ensureTestUsers = async () => {
  try {
    const bcrypt = require('bcryptjs');
    const salt = await bcrypt.genSalt(10);
    const users = [
      { employee_id: 'EMP001', name: 'John Doe', email: 'john@example.com', pin: '123456', is_admin: true },
      { employee_id: 'EMP002', name: 'Jane Smith', email: 'jane@example.com', pin: '5678', is_admin: false },
      { employee_id: 'EMP003', name: 'Mike Johnson', email: 'mike@example.com', pin: '9012', is_admin: false },
    ];

    for (const user of users) {
      const hashedPin = await bcrypt.hash(user.pin, salt);
      const result = await pool.query(
        `INSERT INTO users (employee_id, name, email, pin, is_admin)
         VALUES ($1, $2, $3, $4, $5)
         ON CONFLICT (employee_id) DO UPDATE SET pin = $4, name = $2, is_admin = $5, is_active = true
         RETURNING id, employee_id, LENGTH(pin) as pin_len`,
        [user.employee_id, user.name, user.email, hashedPin, user.is_admin]
      );
      if (result.rows[0]) {
        console.log(`User ${user.employee_id}: pin hash length=${result.rows[0].pin_len}`);
      }
    }

    // Verify one user can authenticate
    const testUser = await pool.query("SELECT pin FROM users WHERE employee_id = 'EMP002'");
    if (testUser.rows.length > 0) {
      const valid = await bcrypt.compare('5678', testUser.rows[0].pin);
      console.log(`Auth verify EMP002/5678: ${valid}`);
    }
    
    console.log('Test users verified.');
  } catch (error) {
    console.error('Ensure users FAILED:', error.message, error.stack);
  }
};

// Start server
const server = app.listen(PORT, async () => {
  console.log(`Server running on port ${PORT}`);
  
  // Startup tasks
  await cleanupSessions();
  await ensureTestUsers();
  try {
    await createWorkOrderTables();
  } catch (error) {
    console.error('Work order table init failed:', error.message);
  }
  importNapsIfNeeded(); // fire-and-forget, runs in background
  
  // Periodic session cleanup every hour
  setInterval(cleanupSessions, 60 * 60 * 1000);

  // Nightly database backup (runs ~2min after boot if last backup is stale,
  // then re-checked every 6 hours)
  scheduleBackups();

  // Daily purge of GPS pings older than 90 days (keeps DB size bounded;
  // attendance records and photos are never purged)
  schedulePurge();

  // Auto clock-out employees who exceeded MAX_HOURS without clocking out
  scheduleAutoClockOut();

  // Globe FSM ingestion (folder / SFTP / HTTP export pickup). No-op unless
  // FSM_SYNC_ENABLED=true, so deployments without FSM credentials stay inert.
  scheduleFsmSync();
});

// Graceful shutdown
const shutdown = async (signal) => {
  console.log(`\n${signal} received. Shutting down gracefully...`);
  server.close(async () => {
    console.log('HTTP server closed.');
    await pool.end();
    console.log('Database pool closed.');
    process.exit(0);
  });
  
  // Force exit after 10 seconds if graceful shutdown hangs
  setTimeout(() => {
    console.error('Forced shutdown after timeout');
    process.exit(1);
  }, 10000);
};

process.on('SIGTERM', () => shutdown('SIGTERM'));
process.on('SIGINT', () => shutdown('SIGINT'));

module.exports = app;
